-- Week 8 extension: request-level audit and plain-English explanations.
-- Apply after agent_schema.sql, agent_schema_week5.sql and agent_schema_week6_7.sql.
-- Additive and idempotent: safe to re-run.
--
-- One agent_requests row is written per natural-language request. It records
-- the whole pipeline in one place: parsed intent, the schema retrieval that
-- grounded the prompt (schema_lookup_log), the final SQL, the Week 5 guardrail
-- verdict, the outcome, and the plain-English response shown to the user.
--
--   agent_sessions 1 ──< agent_requests 1 ──< request_explanations   (weak entity)
--   schema_lookup_log 1 ──< agent_requests
--   agent_requests >──< execution_audit  via request_attempts         (associative)
--
-- execution_audit stays append-only: attempts are linked through
-- request_attempts instead of updating the audit rows after the fact.

CREATE TABLE IF NOT EXISTS agent_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36) NOT NULL,
    turn_no INTEGER NOT NULL,
    request_text TEXT NOT NULL,
    parsed_intent JSONB NOT NULL DEFAULT '{}'::jsonb,
    lookup_id BIGINT,
    action_type VARCHAR(10),
    final_sql TEXT,
    count_sql TEXT,
    plan_confidence NUMERIC(4, 3),
    guardrail_verdict VARCHAR(10),
    effective_verdict VARCHAR(10),
    risk_score NUMERIC(5, 2),
    triggered_rules JSONB NOT NULL DEFAULT '[]'::jsonb,
    escalations JSONB NOT NULL DEFAULT '[]'::jsonb,
    approved BOOLEAN NOT NULL DEFAULT FALSE,
    final_status VARCHAR(20) NOT NULL,
    stop_reason VARCHAR(40) NOT NULL,
    attempts SMALLINT NOT NULL,
    row_count INTEGER,
    affected_rows INTEGER,
    response_headline TEXT NOT NULL,
    response_text TEXT NOT NULL,
    latency_ms NUMERIC(10, 2),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_agent_requests_session
        FOREIGN KEY (session_id)
        REFERENCES agent_sessions (session_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT fk_agent_requests_lookup
        FOREIGN KEY (lookup_id)
        REFERENCES schema_lookup_log (lookup_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,
    CONSTRAINT uq_agent_requests_turn UNIQUE (session_id, turn_no),
    CONSTRAINT chk_agent_requests_action
        CHECK (action_type IS NULL OR action_type IN ('read', 'write', 'ddl', 'unknown')),
    CONSTRAINT chk_agent_requests_verdicts
        CHECK (
            (guardrail_verdict IS NULL OR guardrail_verdict IN ('ALLOW', 'CONFIRM', 'BLOCK'))
            AND (effective_verdict IS NULL OR effective_verdict IN ('ALLOW', 'CONFIRM', 'BLOCK'))
        ),
    CONSTRAINT chk_agent_requests_status
        CHECK (final_status IN ('success', 'blocked', 'needs_approval', 'rolled_back', 'failed')),
    CONSTRAINT chk_agent_requests_attempts CHECK (attempts >= 0),
    CONSTRAINT chk_agent_requests_confidence
        CHECK (plan_confidence IS NULL OR plan_confidence BETWEEN 0 AND 1)
);

-- Associative entity: which execution_audit rows (one per sandboxed attempt)
-- belong to which request.
CREATE TABLE IF NOT EXISTS request_attempts (
    request_id BIGINT NOT NULL,
    audit_id BIGINT NOT NULL,
    attempt_no SMALLINT NOT NULL,

    CONSTRAINT pk_request_attempts PRIMARY KEY (request_id, audit_id),
    CONSTRAINT uq_request_attempts_audit UNIQUE (audit_id),
    CONSTRAINT fk_request_attempts_request
        FOREIGN KEY (request_id)
        REFERENCES agent_requests (request_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_request_attempts_audit
        FOREIGN KEY (audit_id)
        REFERENCES execution_audit (audit_id)
        ON DELETE CASCADE
);

-- Weak entity: the ordered root-cause ("why not") explanations of a request,
-- identified by (request_id, explanation_seq).
CREATE TABLE IF NOT EXISTS request_explanations (
    request_id BIGINT NOT NULL,
    explanation_seq SMALLINT NOT NULL,
    stage VARCHAR(20) NOT NULL,
    code VARCHAR(60) NOT NULL,
    headline TEXT NOT NULL,
    cause TEXT NOT NULL,
    fix TEXT,
    evidence JSONB NOT NULL DEFAULT '{}'::jsonb,

    CONSTRAINT pk_request_explanations PRIMARY KEY (request_id, explanation_seq),
    CONSTRAINT fk_request_explanations_request
        FOREIGN KEY (request_id)
        REFERENCES agent_requests (request_id)
        ON DELETE CASCADE,
    CONSTRAINT chk_request_explanations_stage
        CHECK (stage IN (
            'planning', 'guardrails', 'drift', 'blast_radius', 'approval',
            'execution', 'precommit', 'retry', 'result'
        ))
);

CREATE INDEX IF NOT EXISTS idx_agent_requests_session ON agent_requests (session_id, turn_no);
CREATE INDEX IF NOT EXISTS idx_agent_requests_status ON agent_requests (final_status);
CREATE INDEX IF NOT EXISTS idx_agent_requests_created ON agent_requests (created_at);
CREATE INDEX IF NOT EXISTS idx_request_explanations_code ON request_explanations (code);

-- One row per request with everything a reviewer (or the Week 11 dashboard)
-- needs: retrieval, verdicts, attempts, outcome and the first root cause.
CREATE OR REPLACE VIEW v_request_audit AS
SELECT
    r.request_id,
    r.session_id,
    r.turn_no,
    r.created_at,
    r.request_text,
    r.action_type,
    l.retrieved_tables,
    l.retrieval_score,
    r.final_sql,
    r.guardrail_verdict,
    r.effective_verdict,
    r.risk_score,
    r.approved,
    r.final_status,
    r.stop_reason,
    r.attempts,
    COALESCE(a.sandbox_runs, 0) AS sandbox_runs,
    a.last_execution_status,
    a.last_sqlstate,
    r.row_count,
    r.affected_rows,
    r.response_headline,
    e.code AS root_cause_code,
    e.headline AS root_cause,
    r.latency_ms
FROM agent_requests AS r
LEFT JOIN schema_lookup_log AS l ON l.lookup_id = r.lookup_id
LEFT JOIN LATERAL (
    SELECT
        COUNT(*) AS sandbox_runs,
        (ARRAY_AGG(ea.execution_status ORDER BY ra.attempt_no DESC, ea.audit_id DESC))[1] AS last_execution_status,
        (ARRAY_AGG(ea.sqlstate ORDER BY ra.attempt_no DESC, ea.audit_id DESC))[1] AS last_sqlstate
    FROM request_attempts AS ra
    JOIN execution_audit AS ea ON ea.audit_id = ra.audit_id
    WHERE ra.request_id = r.request_id
) AS a ON TRUE
LEFT JOIN request_explanations AS e
    ON e.request_id = r.request_id AND e.explanation_seq = 1;

GRANT SELECT, INSERT ON agent_requests, request_attempts, request_explanations, schema_lookup_log TO dbm_writer;
GRANT SELECT ON agent_requests, request_attempts, request_explanations, v_request_audit TO dbm_reader;
GRANT SELECT, INSERT, UPDATE, DELETE ON agent_requests, request_attempts, request_explanations TO dbm_admin;
GRANT SELECT ON v_request_audit TO dbm_writer, dbm_admin;
-- The audit trail is append-only for the agent's role.
REVOKE UPDATE, DELETE ON agent_requests, request_attempts, request_explanations FROM dbm_writer;
