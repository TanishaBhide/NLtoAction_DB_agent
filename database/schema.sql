-- Week 1 normalized operational schema for the Online Retail dataset.
-- PostgreSQL syntax is used so the file matches the project abstract.

DROP TRIGGER IF EXISTS trg_invoices_set_status ON invoices;
DROP TRIGGER IF EXISTS trg_invoice_items_validate_unit_price ON invoice_items;
DROP FUNCTION IF EXISTS set_invoice_status_from_invoice_no();
DROP FUNCTION IF EXISTS validate_invoice_item_unit_price();

DROP TABLE IF EXISTS invoice_items CASCADE;
DROP TABLE IF EXISTS invoices CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS customers CASCADE;

CREATE TABLE customers (
    customer_id VARCHAR(20) PRIMARY KEY,
    country VARCHAR(100) NOT NULL
);

CREATE TABLE products (
    stock_code VARCHAR(50) PRIMARY KEY,
    description VARCHAR(255)
);

CREATE TABLE invoices (
    invoice_no VARCHAR(20) PRIMARY KEY,
    invoice_date TIMESTAMP NOT NULL,
    customer_id VARCHAR(20),
    status VARCHAR(20) NOT NULL DEFAULT 'completed',

    CONSTRAINT fk_invoices_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT chk_invoices_status
        CHECK (status IN ('completed', 'cancelled', 'adjustment'))
);

CREATE TABLE invoice_items (
    invoice_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no VARCHAR(20) NOT NULL,
    stock_code VARCHAR(50) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,

    CONSTRAINT fk_invoice_items_invoice
        FOREIGN KEY (invoice_no)
        REFERENCES invoices (invoice_no)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_invoice_items_product
        FOREIGN KEY (stock_code)
        REFERENCES products (stock_code)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_invoice_items_quantity
        CHECK (quantity <> 0)
);

CREATE OR REPLACE FUNCTION set_invoice_status_from_invoice_no()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.invoice_no LIKE 'C%' THEN
        NEW.status := 'cancelled';
    ELSIF NEW.invoice_no LIKE 'A%' THEN
        NEW.status := 'adjustment';
    ELSE
        NEW.status := 'completed';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_invoices_set_status
BEFORE INSERT OR UPDATE OF invoice_no ON invoices
FOR EACH ROW
EXECUTE FUNCTION set_invoice_status_from_invoice_no();

CREATE OR REPLACE FUNCTION validate_invoice_item_unit_price()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    parent_status VARCHAR(20);
BEGIN
    IF NEW.unit_price < 0 THEN
        SELECT status
        INTO parent_status
        FROM invoices
        WHERE invoice_no = NEW.invoice_no;

        IF parent_status IS NULL THEN
            RAISE EXCEPTION 'invoice % does not exist', NEW.invoice_no;
        END IF;

        IF parent_status <> 'adjustment' THEN
            RAISE EXCEPTION 'negative unit_price is only allowed for adjustment invoices';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_invoice_items_validate_unit_price
BEFORE INSERT OR UPDATE OF unit_price, invoice_no ON invoice_items
FOR EACH ROW
EXECUTE FUNCTION validate_invoice_item_unit_price();

CREATE INDEX idx_invoices_customer_id
    ON invoices (customer_id);

CREATE INDEX idx_invoice_items_invoice_no
    ON invoice_items (invoice_no);

CREATE INDEX idx_invoice_items_stock_code
    ON invoice_items (stock_code);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dbm_admin') THEN
        CREATE ROLE dbm_admin NOLOGIN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dbm_writer') THEN
        CREATE ROLE dbm_writer NOLOGIN;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dbm_reader') THEN
        CREATE ROLE dbm_reader NOLOGIN;
    END IF;
END
$$;

GRANT USAGE ON SCHEMA public TO dbm_admin, dbm_writer, dbm_reader;
GRANT SELECT, INSERT, UPDATE, DELETE ON customers, products, invoices, invoice_items TO dbm_admin;
GRANT SELECT, INSERT, UPDATE ON customers, products, invoices, invoice_items TO dbm_writer;
GRANT SELECT ON customers, products, invoices, invoice_items TO dbm_reader;

GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO dbm_admin, dbm_writer;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO dbm_admin;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE ON TABLES TO dbm_writer;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT ON TABLES TO dbm_reader;