-- Week 5 extension for guardrail policies, assessments, and approvals.
-- Apply after database/agent_schema.sql; existing policy and sensitivity
-- tables are extended rather than duplicated.

ALTER TABLE policy_rules
    ADD COLUMN IF NOT EXISTS rule_type VARCHAR(120),
    ADD COLUMN IF NOT EXISTS description TEXT;

UPDATE policy_rules
SET rule_type = rule_name
WHERE rule_type IS NULL;

UPDATE policy_rules
SET description = rule_description
WHERE description IS NULL;

ALTER TABLE policy_rules
    ALTER COLUMN rule_type SET NOT NULL,
    ALTER COLUMN description SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_policy_rules_rule_type
    ON policy_rules (rule_type);

ALTER TABLE policy_rules
    DROP CONSTRAINT IF EXISTS chk_policy_rules_severity;

UPDATE policy_rules
SET severity = UPPER(severity)
WHERE UPPER(severity) IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL');

ALTER TABLE policy_rules
    ALTER COLUMN severity SET DEFAULT 'MEDIUM',
    ADD CONSTRAINT chk_policy_rules_severity
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL', 'low', 'medium', 'high', 'critical'));

ALTER TABLE column_sensitivity
    ADD COLUMN IF NOT EXISTS rule_id BIGINT REFERENCES policy_rules (rule_id);

UPDATE column_sensitivity
SET sensitivity_level = UPPER(sensitivity_level)
WHERE UPPER(sensitivity_level) IN ('LOW', 'MEDIUM', 'HIGH');

ALTER TABLE column_sensitivity
    ALTER COLUMN sensitivity_level SET DEFAULT 'LOW',
    DROP CONSTRAINT IF EXISTS chk_column_sensitivity_level;

ALTER TABLE column_sensitivity
    ADD CONSTRAINT chk_column_sensitivity_level
        CHECK (sensitivity_level IN ('LOW', 'MEDIUM', 'HIGH', 'normal'));

CREATE TABLE IF NOT EXISTS risk_assessment (
    assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36),
    risk_score DECIMAL(5, 2) NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    verdict VARCHAR(10) NOT NULL CHECK (verdict IN ('ALLOW', 'CONFIRM', 'BLOCK')),
    evaluated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS checked_against (
    assessment_id BIGINT NOT NULL REFERENCES risk_assessment (assessment_id) ON DELETE CASCADE,
    rule_id BIGINT NOT NULL REFERENCES policy_rules (rule_id),
    PRIMARY KEY (assessment_id, rule_id)
);

CREATE TABLE IF NOT EXISTS approval_request (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL UNIQUE REFERENCES risk_assessment (assessment_id) ON DELETE CASCADE,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    resolved_at TIMESTAMP
);

