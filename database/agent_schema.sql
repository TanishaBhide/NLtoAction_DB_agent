-- Companion agent-system schema for the database admin agent.
-- This gives later weeks a place to store sessions, policies, lookups, audits,
-- and compensation records.

-- Week 8/9 tables reference the tables below; drop them first so a reset
-- recreates them (with their foreign keys) instead of leaving orphans.
DROP VIEW IF EXISTS v_request_audit CASCADE;  -- also drops the web app's v_dba_activity
DROP TABLE IF EXISTS blast_radius_previews CASCADE;
DROP TABLE IF EXISTS drift_assessments CASCADE;
DROP TABLE IF EXISTS request_explanations CASCADE;
DROP TABLE IF EXISTS request_attempts CASCADE;
DROP TABLE IF EXISTS agent_requests CASCADE;
DROP TABLE IF EXISTS compensation_ledger CASCADE;
DROP TABLE IF EXISTS execution_audit CASCADE;
DROP TABLE IF EXISTS schema_lookup_log CASCADE;
DROP TABLE IF EXISTS policy_rule_columns CASCADE;
DROP TABLE IF EXISTS column_sensitivity CASCADE;
DROP TABLE IF EXISTS policy_rules CASCADE;
DROP TABLE IF EXISTS session_events CASCADE;
DROP TABLE IF EXISTS agent_sessions CASCADE;

CREATE TABLE agent_sessions (
    session_id VARCHAR(36) PRIMARY KEY,
    user_label VARCHAR(100),
    purpose VARCHAR(255),
    current_state JSONB NOT NULL DEFAULT '{}'::jsonb,
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMP,
    session_status VARCHAR(20) NOT NULL DEFAULT 'active',

    CONSTRAINT chk_agent_sessions_status
        CHECK (session_status IN ('active', 'ended', 'expired'))
);

-- Weak entity: each event depends on a parent session and is identified by the
-- pair (session_id, event_seq).
CREATE TABLE session_events (
    session_id VARCHAR(36) NOT NULL,
    event_seq INTEGER NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    event_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_session_events PRIMARY KEY (session_id, event_seq),
    CONSTRAINT fk_session_events_session
        FOREIGN KEY (session_id)
        REFERENCES agent_sessions (session_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE TABLE policy_rules (
    rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_name VARCHAR(120) NOT NULL UNIQUE,
    action_type VARCHAR(30) NOT NULL,
    rule_description TEXT NOT NULL,
    severity VARCHAR(20) NOT NULL DEFAULT 'medium',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    requires_confirmation BOOLEAN NOT NULL DEFAULT FALSE,
    rationale TEXT,

    CONSTRAINT chk_policy_rules_action_type
        CHECK (action_type IN ('read', 'write', 'ddl')),
    CONSTRAINT chk_policy_rules_severity
        CHECK (severity IN ('low', 'medium', 'high', 'critical'))
);

CREATE TABLE column_sensitivity (
    sensitivity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name VARCHAR(128) NOT NULL,
    column_name VARCHAR(128) NOT NULL,
    sensitivity_level VARCHAR(20) NOT NULL DEFAULT 'normal',
    read_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    write_allowed BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,

    CONSTRAINT uq_column_sensitivity UNIQUE (table_name, column_name)
);

-- Many-to-many bridge: a policy rule can govern many columns and a column can
-- be covered by many rules.
CREATE TABLE policy_rule_columns (
    rule_id BIGINT NOT NULL,
    sensitivity_id BIGINT NOT NULL,

    CONSTRAINT pk_policy_rule_columns PRIMARY KEY (rule_id, sensitivity_id),
    CONSTRAINT fk_policy_rule_columns_rule
        FOREIGN KEY (rule_id)
        REFERENCES policy_rules (rule_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT fk_policy_rule_columns_sensitivity
        FOREIGN KEY (sensitivity_id)
        REFERENCES column_sensitivity (sensitivity_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE TABLE schema_lookup_log (
    lookup_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36),
    user_query TEXT NOT NULL,
    retrieved_tables JSONB NOT NULL DEFAULT '[]'::jsonb,
    retrieved_columns JSONB NOT NULL DEFAULT '[]'::jsonb,
    retrieval_score NUMERIC(5, 4),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_schema_lookup_session
        FOREIGN KEY (session_id)
        REFERENCES agent_sessions (session_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

CREATE TABLE execution_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36),
    lookup_id BIGINT,
    intent_text TEXT NOT NULL,
    generated_sql TEXT,
    guardrail_verdict VARCHAR(20) NOT NULL,
    execution_status VARCHAR(20) NOT NULL,
    risk_score NUMERIC(5, 2),
    error_message TEXT,
    transaction_id VARCHAR(64),
    affected_row_count INTEGER NOT NULL DEFAULT 0,
    executed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_execution_audit_session
        FOREIGN KEY (session_id)
        REFERENCES agent_sessions (session_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,
    CONSTRAINT fk_execution_audit_lookup
        FOREIGN KEY (lookup_id)
        REFERENCES schema_lookup_log (lookup_id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,
    CONSTRAINT chk_execution_audit_guardrail_verdict
        CHECK (guardrail_verdict IN ('allow', 'confirm', 'block')),
    CONSTRAINT chk_execution_audit_status
        CHECK (execution_status IN ('not_executed', 'committed', 'rolled_back', 'failed'))
);

CREATE TABLE compensation_ledger (
    compensation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id BIGINT NOT NULL,
    compensation_sql TEXT NOT NULL,
    compensation_status VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_compensation_audit
        FOREIGN KEY (audit_id)
        REFERENCES execution_audit (audit_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT chk_compensation_status
        CHECK (compensation_status IN ('pending', 'applied', 'not_required', 'failed'))
);

CREATE INDEX idx_agent_sessions_status ON agent_sessions (session_status);
CREATE INDEX idx_session_events_created_at ON session_events (created_at);
CREATE INDEX idx_policy_rules_action_type ON policy_rules (action_type);
CREATE INDEX idx_schema_lookup_session ON schema_lookup_log (session_id);
CREATE INDEX idx_execution_audit_session ON execution_audit (session_id);

